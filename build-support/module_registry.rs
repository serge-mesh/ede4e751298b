// The module registry scan shared by the build scripts of picket-core (download modules) and
// picket-lookup (lookup modules), providers.md §1: each `include!`s this file. It finds the
// module directories, checks their ids and renders the registry source that declares each module
// with `#[path]` and lists one boxed `Module::default()` each. No linker tricks, no `unsafe`.
//
// Paths are spelled out in full: the including build script has its own `use` lines.

/// Rust keywords (strict, reserved and weak ones that can't name a module).
const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop",
    "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return", "self", "static",
    "struct", "super", "trait", "true", "try", "type", "typeof", "unsafe", "unsized", "use", "virtual",
    "where", "while", "yield",
];

/// The longest module id.
const MAX_ID: usize = 32;

/// Module id → path of its `mod.rs`, for every directory under `dir`. Fails on a directory
/// without `mod.rs`, an invalid id ([`check_id`]), a duplicate id, or no module at all.
fn scan(dir: &std::path::Path) -> Result<std::collections::BTreeMap<String, std::path::PathBuf>, String> {
    let mut modules = std::collections::BTreeMap::new();
    let entries = std::fs::read_dir(dir).map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|e| format!("cannot stat {}: {e}", path.display()))?;
        if !file_type.is_dir() {
            continue; // the framework's own files, or a README, beside the module directories
        }
        let name = entry.file_name();
        let Some(id) = name.to_str() else {
            return Err(format!("{}: directory name isn't UTF-8", path.display()));
        };
        if id.starts_with('.') {
            continue;
        }
        check_id(id).map_err(|e| format!("{}: invalid module id {id:?}: {e}", path.display()))?;
        let mod_rs = path.join("mod.rs");
        if !mod_rs.is_file() {
            return Err(format!("{}: missing mod.rs", path.display()));
        }
        println!("cargo:rerun-if-changed={}", path.display());
        println!("cargo:rerun-if-changed={}", mod_rs.display());
        if modules.insert(id.to_owned(), mod_rs).is_some() {
            return Err(format!("duplicate module id {id:?}"));
        }
    }
    if modules.is_empty() {
        return Err(format!("no modules under {}", dir.display()));
    }
    Ok(modules)
}

/// A module id is lowercase `[a-z0-9_]` (providers.md §1), at most 32 bytes, and must also name
/// a Rust module: no leading digit, not `_` alone, not a keyword.
fn check_id(id: &str) -> Result<(), &'static str> {
    if id.is_empty() || id.len() > MAX_ID {
        return Err("must be 1 to 32 bytes");
    }
    if !id
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
    {
        return Err("only a-z, 0-9 and _ are allowed");
    }
    if id.as_bytes()[0].is_ascii_digit() {
        return Err("can't start with a digit");
    }
    if id == "_" || KEYWORDS.contains(&id) {
        return Err("is a Rust keyword");
    }
    Ok(())
}

/// The registry source: a `@generated` line naming `origin`, one `#[path]` module per entry,
/// `pub const {ids}: &[&str]` with every id, and `pub fn {all}()` returning one boxed
/// `Module::default()` per module as `Box<dyn {module_trait}>`, all sorted by id.
fn render_registry(
    origin: &str,
    modules: &std::collections::BTreeMap<String, std::path::PathBuf>,
    ids: &str,
    all: &str,
    module_trait: &str,
) -> Result<String, String> {
    use std::fmt::Write as _;
    let mut s = String::new();
    let _ = writeln!(s, "// @generated by {origin} (providers.md §1).\n");
    for (id, path) in modules {
        let path = path
            .to_str()
            .ok_or_else(|| format!("{}: path isn't UTF-8", path.display()))?;
        let _ = writeln!(s, "#[path = {path:?}]\npub mod {id};");
    }
    let _ = write!(s, "\n/// Every module id, sorted.\npub const {ids}: &[&str] = &[");
    for id in modules.keys() {
        let _ = write!(s, "{id:?}, ");
    }
    s.push_str("];\n\n");
    let _ = writeln!(
        s,
        "/// One boxed `Module::default()` per module directory, sorted by id.\n\
         pub fn {all}() -> ::std::vec::Vec<::std::boxed::Box<dyn {module_trait}>> {{\n    ::std::vec!["
    );
    for id in modules.keys() {
        let _ = writeln!(
            s,
            "        ::std::boxed::Box::new(<{id}::Module as ::core::default::Default>::default()),"
        );
    }
    s.push_str("    ]\n}\n");
    Ok(s)
}

/// Scans `dir` and renders its registry ([`render_registry`]); on any error, stops the build with
/// the reason (providers.md §1), prefixed by `what`.
fn registry_or_exit(
    what: &str,
    dir: &std::path::Path,
    render: impl FnOnce(&std::collections::BTreeMap<String, std::path::PathBuf>) -> Result<String, String>,
) -> String {
    match scan(dir).and_then(|m| render(&m)) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("{what}: {e}");
            std::process::exit(1);
        }
    }
}
