//! The table-driven parity corpus (PARITY.md): rule × name expectations recorded from urlfilter
//! v0.23 (through `tools/urlfilter-oracle`) in `fixtures/rules/urlfilter-expectations.tsv`, checked
//! without Go. Rows whose decision a deliberate exception of rules.md §3 changes are not recorded.
//!
//! Regenerate with `PICKET_URLFILTER_ORACLE=<oracle> PICKET_WRITE_PARITY_TABLE=1 cargo test -p
//! picket-rules --test parity_table`.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::cast_possible_truncation,
    clippy::cast_possible_wrap,
    clippy::cast_sign_loss,
    reason = "integration test code: a failed unwrap or expect is the test's report, and it may cast freely"
)]

mod common;

use std::fmt::Write as _;
use std::net::IpAddr;

use common::{
    Case, Group, Query, Target, build, decision, evaluate, normalise_oracle, parse_rules, run_oracle,
};
use picket_rules::matcher::BundleMatcher;

const TABLE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../fixtures/rules/urlfilter-expectations.tsv"
);

/// Names whose negative results are worth recording for every rule.
const NEGATIVE_PROBES: &[&str] = &[
    "notexample.com",
    "example.com.evil.net",
    "www.example.com",
    "example.net",
    "1.2.3.4",
];

fn host_field(q: &Query) -> String {
    match &q.target {
        Target::Name(l) => format!(
            "name:{}",
            picket_api::names::encode_labels(l.iter().map(Vec::as_slice))
        ),
        Target::Ip(ip) => format!("ip:{ip}"),
    }
}

fn selected(case: &Case, qi: usize, q: &Query, d: &str) -> bool {
    // Single rules, the parity examples, rewrite-order cases and `$denyallow` entities.
    if case.group != Group::Main || !case.id.starts_with(['s', 'x', 'o', 'e']) {
        return false;
    }
    if case.id.starts_with(['o', 'e']) {
        return true;
    }
    let ctx = qi % 6;
    let interesting = d != "none"
        || matches!(&q.target, Target::Name(l) if NEGATIVE_PROBES.contains(&l.iter().map(|x| String::from_utf8_lossy(x).into_owned()).collect::<Vec<_>>().join(".").as_str()));
    let rule_has_modifier = case.rules.iter().any(|r| r.contains('$'));
    interesting && (ctx == 0 || (rule_has_modifier && ctx <= 2) || matches!(q.target, Target::Ip(_)))
}

#[test]
fn recorded_expectations() {
    if std::env::var_os("PICKET_WRITE_PARITY_TABLE").is_some() {
        write_table();
        return;
    }
    let text = std::fs::read_to_string(TABLE).expect("fixtures/rules/urlfilter-expectations.tsv");
    let mut rows = 0usize;
    let mut failures = Vec::new();
    let mut cache: Option<(String, BundleMatcher)> = None;
    for line in text.lines().filter(|l| !l.starts_with('#') && !l.is_empty()) {
        let f: Vec<&str> = line.split('\t').collect();
        let [rules, host, qtype, ip, name, tags, expected] = f.as_slice() else {
            panic!("bad row {line}")
        };
        if cache.as_ref().is_none_or(|(k, _)| k != rules) {
            let lines: Vec<String> = rules.split(" ⏎ ").map(String::from).collect();
            cache = Some((rules.to_string(), common::block_matcher(parse_rules(&lines))));
        }
        let m = &cache.as_ref().unwrap().1;
        let target = if let Some(n) = host.strip_prefix("name:") {
            Target::Name(picket_api::names::decode_labels(n).unwrap())
        } else {
            Target::Ip(host.strip_prefix("ip:").unwrap().parse::<IpAddr>().unwrap())
        };
        let q = Query {
            target,
            qtype: qtype.parse().unwrap(),
            client_ip: (*ip != "-").then(|| ip.parse().unwrap()),
            client_name: (*name != "-").then(|| name.to_string()),
            tags: if *tags == "-" {
                vec![]
            } else {
                tags.split(',').map(String::from).collect()
            },
        };
        let got = decision(&evaluate(m, &q).outcome);
        rows += 1;
        if got != *expected {
            failures.push(format!(
                "{rules} | {host} qtype={qtype}: picket={got} urlfilter={expected}"
            ));
        }
    }
    assert!(rows > 1000, "table too small: {rows}");
    assert!(
        failures.is_empty(),
        "{} of {rows} rows differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

fn write_table() {
    let bin = std::env::var("PICKET_URLFILTER_ORACLE").expect("PICKET_URLFILTER_ORACLE");
    let cases = build();
    let oracle = run_oracle(&bin, &cases);
    let mut out = String::from(
        "# rules (joined by ' ⏎ ')\ttarget\tqtype\tclient ip\tclient name\ttags\turlfilter v0.23 decision (AdGuard Home matchHost)\n# Generated by crates/picket-rules/tests/parity_table.rs from tools/urlfilter-oracle; see PARITY.md.\n",
    );
    for (ci, case) in cases.iter().enumerate() {
        let m = common::block_matcher(parse_rules(&case.rules));
        for (qi, q) in case.queries.iter().enumerate() {
            let d = normalise_oracle(&oracle[ci][qi]);
            if q.unusual() || !selected(case, qi, q, &d) {
                continue;
            }
            let res = evaluate(&m, q);
            if res.matches.iter().any(|mm| m.rules()[mm.rule].spec.extension) {
                continue;
            }
            let _ = writeln!(
                out,
                "{}\t{}\t{}\t{}\t{}\t{}\t{}",
                case.rules.join(" ⏎ "),
                host_field(q),
                q.qtype,
                q.client_ip.map_or("-".to_string(), |i| i.to_string()),
                q.client_name.as_deref().unwrap_or("-"),
                if q.tags.is_empty() {
                    "-".to_string()
                } else {
                    q.tags.join(",")
                },
                d
            );
        }
    }
    std::fs::write(TABLE, out).unwrap();
}
